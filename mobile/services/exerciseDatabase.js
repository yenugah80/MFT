/** Everything a query can match against, lowercased once per exercise */
const searchIndex = new Map(
  EXERCISES.map((ex) => [
    ex.id,
    [ex.name, ex.description, ex.muscleGroup, ex.equipment, ...(ex.aliases || [])]
      .join(' ')
      .toLowerCase(),
  ])
);

/** Levenshtein distance, capped early — used only for the typo fallback */
const editDistance = (a, b, max) => {
  if (Math.abs(a.length - b.length) > max) return max + 1;
  let prev = Array.from({ length: b.length + 1 }, (_, i) => i);
  for (let i = 1; i <= a.length; i += 1) {
    const row = [i];
    let rowMin = i;
    for (let j = 1; j <= b.length; j += 1) {
      const cost = a[i - 1] === b[j - 1] ? 0 : 1;
      row[j] = Math.min(prev[j] + 1, row[j - 1] + 1, prev[j - 1] + cost);
      rowMin = Math.min(rowMin, row[j]);
    }
    if (rowMin > max) return max + 1;
    prev = row;
  }
  return prev[b.length];
};

/** How much slack a typo gets, by word length */
const typoTolerance = (word) => (word.length >= 8 ? 2 : word.length >= 5 ? 1 : 0);

/**
 * Search exercises by name, description, muscle group, equipment or alias.
 * Falls back to fuzzy word matching so "threadmill" still finds the treadmill.
 */
export const searchExercises = (query) => {
  const trimmed = (query || '').trim().toLowerCase();
  if (!trimmed) return EXERCISES;

  const exact = EXERCISES.filter((ex) => searchIndex.get(ex.id).includes(trimmed));
  if (exact.length > 0) return exact;

  const queryWords = trimmed.split(/\s+/).filter(Boolean);
  return EXERCISES.filter((ex) => {
    const words = searchIndex.get(ex.id).split(/[^a-z0-9]+/).filter(Boolean);
    return queryWords.every((qw) => {
      const tolerance = typoTolerance(qw);
      if (tolerance === 0) return words.some((w) => w.startsWith(qw));
      return words.some((w) => editDistance(qw, w, tolerance) <= tolerance);
    });
  });
};

/**
 * Combined filter used by the Activity screen: free-text query, modality
 * category and focus (muscle group / equipment) chips.
 */
export const filterExercises = ({ query, category, focusKey } = {}) => {
  let results = query ? searchExercises(query) : EXERCISES;

  if (category) {
    results = results.filter((ex) => ex.category === category);
  }

  if (focusKey) {
    const focus = FOCUS_FILTERS.find((f) => f.key === focusKey);
    if (focus) results = results.filter(focus.match);
  }

  return results;
};


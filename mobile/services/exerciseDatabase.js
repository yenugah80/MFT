/**
 * Calculate calories burned based on duration, weight and intensity.
 * Formula: Calories = MET × weight(kg) × time(hours)
 *
 * Uses the same MET table the API logs with, so the preview in the modal and
 * the number that lands on the activity card agree.
 */
export const calculateCalories = (exercise, durationMinutes, weightKg = REFERENCE_WEIGHT_KG, intensityLevel = 'MODERATE') => {
  const met = getLoggedMet(exercise, INTENSITY_LEVELS[intensityLevel] ? intensityLevel : 'MODERATE');
  const hours = durationMinutes / 60;
  return Math.round(met * weightKg * hours);
};


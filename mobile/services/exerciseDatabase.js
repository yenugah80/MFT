/**
 * Intensity levels. Keys mirror the backend's light/moderate/vigorous buckets
 * so the previewed estimate and the calories the API logs stay in step.
 */
export const INTENSITY_LEVELS = {
  LIGHT: { label: 'Light', multiplier: 0.7, color: '#10B981' },
  MODERATE: { label: 'Moderate', multiplier: 1.0, color: '#F59E0B' },
  VIGOROUS: { label: 'Vigorous', multiplier: 1.3, color: '#EF4444' },
};

/**
 * Rows logged before the picker matched the backend's buckets still hold
 * 'low' / 'high' / 'very_high'. Map them rather than silently showing every
 * historic activity as "Moderate".
 */
const LEGACY_INTENSITY_KEYS = {
  LOW: 'LIGHT',
  HIGH: 'VIGOROUS',
  VERY_HIGH: 'VIGOROUS',
};

/**
 * Resolve any stored intensity value to a level, old or new.
 * @param {string} value - e.g. 'moderate', 'very_high', 'VIGOROUS'
 */
export const resolveIntensity = (value) => {
  const key = String(value || '').toUpperCase();
  return INTENSITY_LEVELS[key] || INTENSITY_LEVELS[LEGACY_INTENSITY_KEYS[key]] || INTENSITY_LEVELS.MODERATE;
};

